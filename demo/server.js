function loadThemes() {
    let themes = {};

    // Load standard themes (checked in / generated by Docker build)
    const standardPath = path.join(repoRoot, 'pureadmin.json');
    if (fs.existsSync(standardPath)) {
        const standard = JSON.parse(fs.readFileSync(standardPath, 'utf-8'));
        themes = { ...themes, ...standard.themes };
    }

    // Merge user's private themes (gitignored)
    const localPath = path.join(repoRoot, '.pureadmin.json');
    if (fs.existsSync(localPath)) {
        const local = JSON.parse(fs.readFileSync(localPath, 'utf-8'));
        themes = { ...themes, ...local.themes };
    }

    // Resolve paths and validate
    const resolved = {};
    for (const [name, config] of Object.entries(themes)) {
        // Support both formats:
        //   Old: "audi": "../path/to/audi"
        //   New: "audi": { "path": "../path/to/audi" } or "audi": {}
        let themePath;
        if (typeof config === 'string') {
            themePath = config;
        } else if (config && config.path) {
            themePath = config.path;
        } else {
            // No path — check ./themes/{name} (downloaded themes)
            themePath = path.join('themes', name);
        }

        const absPath = path.resolve(repoRoot, themePath);
        const distPath = path.join(absPath, 'dist');
        if (fs.existsSync(distPath)) {
            resolved[name] = distPath;
        } else {
            console.warn(`Theme "${name}" not found at ${absPath}, skipping`);
        }
    }

    return resolved;
}

const themePackages = loadThemes();

// Negative cache: slug -> timestamp of last failed attempt
const failedThemes = new Map();
const FAILED_THEME_TTL_MS = 10 * 60 * 1000; // 10 minutes

// Downloads a theme on demand from pureadmin.io and registers it
async function ensureTheme(themeName) {
    if (themePackages[themeName]) return true;

    // Only allow safe slug characters
    if (!/^[a-z0-9-]+$/.test(themeName)) return false;

    // Check negative cache
    const failedAt = failedThemes.get(themeName);
    if (failedAt && Date.now() - failedAt < FAILED_THEME_TTL_MS) return false;

    console.log(`Theme "${themeName}" not found locally, downloading from ${PUREADMIN_API}...`);

    try {
        const res = await fetch(`${PUREADMIN_API}/api/themes/${themeName}/download`);
        if (!res.ok) {
            console.warn(`Download failed for "${themeName}": ${res.status}`);
            failedThemes.set(themeName, Date.now());
            return false;
        }

        const zipPath = path.join('/tmp', `${themeName}.zip`);
        const themePath = path.join(repoRoot, 'themes', themeName);

        const buffer = Buffer.from(await res.arrayBuffer());
        fs.writeFileSync(zipPath, buffer);

        fs.mkdirSync(themePath, { recursive: true });
        execFileSync('unzip', ['-o', zipPath, '-d', themePath], { stdio: 'ignore' });
        fs.unlinkSync(zipPath);

        // Raw theme ZIPs have css/, but demo server expects dist/
        const cssPath = path.join(themePath, 'css');
        const distPath = path.join(themePath, 'dist');
        if (fs.existsSync(cssPath) && !fs.existsSync(distPath)) {
            fs.renameSync(cssPath, distPath);
        }

        if (fs.existsSync(distPath)) {
            // Published ZIPs ship a full theme.json (modes, colorVariants,
            // features etc.). Only fall back to API metadata if the ZIP
            // didn't include one — overwriting a complete manifest with
            // the API's trimmed record was stripping modes/variants and
            // breaking the settings panel.
            const manifestPath = path.join(themePath, 'theme.json');
            if (!fs.existsSync(manifestPath)) {
                try {
                    const metaRes = await fetch(`${PUREADMIN_API}/api/themes/${themeName}`);
                    if (metaRes.ok) {
                        const { theme } = await metaRes.json();
                        if (theme) {
                            fs.writeFileSync(manifestPath, JSON.stringify(theme, null, 2));
                        }
                    }
                } catch (e) {
                    console.warn(`Could not fetch metadata for "${themeName}":`, e.message);
                }
            }

            themePackages[themeName] = distPath;
            console.log(`Theme "${themeName}" downloaded and registered.`);
            return true;
        }

        console.warn(`Theme "${themeName}" extracted but no dist/ found.`);
        failedThemes.set(themeName, Date.now());
        return false;
    } catch (e) {
        console.error(`Failed to download theme "${themeName}":`, e.message);
        failedThemes.set(themeName, Date.now());
        return false;
    }
}

